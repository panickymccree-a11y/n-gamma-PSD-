`timescale 1ns/1ps

// Optional three-point parabolic peak-height interpolator.
//
// The Divider Generator is deliberately isolated here.  Its generated
// latency is 30 clocks for the checked-in Vivado 2020.2 configuration, but the
// wrapper uses its output TVALID and TUSER rather than relying on that number
// in the event path.  A single event is held in flight, which is acceptable
// because acquisition windows are much longer than the finalizer latency.
module mca_peak_interpolator (
  input  logic         clk,
  input  logic         rst_n,
  input  logic         flush,
  input  logic         enable,
  input  logic         submit,
  input  logic [13:0]  raw_peak,
  input  logic [13:0]  left_sample,
  input  logic [13:0]  center_sample,
  input  logic [13:0]  right_sample,
  input  logic         candidate_valid,
  input  logic         invalid_overrange,
  input  logic [47:0]  timestamp,
  input  logic [23:0]  integral,
  input  logic [7:0]   flags,
  output logic         busy,
  output logic         result_valid,
  output logic [95:0]  event_data,
  output logic [13:0]  histogram_peak,
  output logic [23:0]  histogram_integral
);
  logic issue_q;
  logic simple_pending_q;
  logic [127:0] simple_user_q;
  logic [127:0] divider_user_q;
  logic [27:0] divider_dividend_q;
  logic [15:0] divider_divisor_q;

  // Three short arithmetic stages keep the 125 MHz path bounded:
  //   submit capture -> delta/curvature -> DSP square -> divider input.
  // The first stage is especially important because candidate selection lives
  // in the acquisition block and can otherwise be placed in front of the
  // multiplier in one long path.
  logic capture_pending_q;
  logic math_pending_q;
  logic [13:0] capture_raw_q;
  logic [13:0] capture_left_q;
  logic [13:0] capture_center_q;
  logic [13:0] capture_right_q;
  logic capture_valid_q;
  logic capture_overrange_q;
  logic [47:0] capture_timestamp_q;
  logic [23:0] capture_integral_q;
  logic [7:0] capture_flags_q;

  logic [13:0] math_raw_q;
  logic [13:0] math_delta_abs_q;
  logic [15:0] math_divisor_q;
  logic math_fallback_q;
  logic [47:0] math_timestamp_q;
  logic [23:0] math_integral_q;
  logic [7:0] math_flags_q;

  logic signed [14:0] capture_delta_signed;
  logic [13:0] capture_delta_abs;
  logic signed [15:0] capture_curvature_signed;
  logic [15:0] capture_divisor;
  logic capture_fallback;
  logic [27:0] math_square_value;

  logic [31:0] quotient_value;
  logic [15:0] remainder_value;
  logic [31:0] correction_value;
  logic [32:0] peak_sum;
  logic [15:0] result_peak_q2;
  logic [7:0] result_flags;

  logic divider_valid;
  logic [127:0] divider_user_out;
  logic [47:0] divider_data_out;
  logic result_pending_q;
  logic [127:0] result_user_q;
  logic [47:0] result_data_q;

  assign capture_delta_signed = $signed({1'b0, capture_left_q}) -
                                $signed({1'b0, capture_right_q});
  assign capture_delta_abs = capture_delta_signed[14]
                           ? -capture_delta_signed : capture_delta_signed;
  assign capture_curvature_signed = $signed({1'b0, capture_center_q, 1'b0}) -
                                    $signed({1'b0, capture_left_q}) -
                                    $signed({1'b0, capture_right_q});
  // Extend before shifting/multiplying.  Without the explicit extension the
  // expression width can truncate the MSB in SystemVerilog, which is only
  // visible for the largest legal ADC excursions.
  assign capture_divisor = capture_curvature_signed[15] ? 16'd1
                         : ({1'b0, capture_curvature_signed[14:0]} << 1);
  assign capture_fallback = !capture_valid_q || capture_overrange_q ||
                            capture_curvature_signed <= 0;
  assign math_square_value = {14'd0, math_delta_abs_q} *
                             {14'd0, math_delta_abs_q};

  // Divider Generator v5.1, generated by Vivado 2020.2.  The quotient is
  // carried in bits [47:16], the remainder in [15:0].
  mca_peak_divider u_divider (
    .aclk(clk),
    .s_axis_divisor_tvalid(issue_q),
    .s_axis_divisor_tdata(divider_divisor_q),
    .s_axis_dividend_tvalid(issue_q),
    .s_axis_dividend_tuser(divider_user_q),
    .s_axis_dividend_tdata({4'd0, divider_dividend_q}),
    .m_axis_dout_tvalid(divider_valid),
    .m_axis_dout_tuser(divider_user_out),
    .m_axis_dout_tdata(divider_data_out)
  );

  // Capture the Divider result before rounding and event packing so its
  // remainder path is not combined with the 96-bit event register path.
  assign quotient_value = result_data_q[47:16];
  assign remainder_value = result_data_q[15:0];
  assign correction_value = quotient_value +
                            ((({1'b0, remainder_value} << 1) >=
                              {1'b0, result_user_q[117:102]}) ? 32'd1 : 32'd0);
  assign peak_sum = {17'd0, result_user_q[21:8], 2'b00} +
                    {1'b0, correction_value};

  always_comb begin
    if (result_user_q[7]) begin
      result_peak_q2 = {result_user_q[21:8], 2'b00};
      result_flags = result_user_q[101:94];
    end else if (peak_sum > 17'h0FFFF) begin
      result_peak_q2 = 16'hFFFF;
      result_flags = result_user_q[101:94] | mca_pkg::EVT_OVERFLOW;
    end else begin
      result_peak_q2 = peak_sum[15:0];
      result_flags = result_user_q[101:94];
    end
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n || flush) begin
      busy <= 1'b0;
      result_valid <= 1'b0;
      event_data <= '0;
      histogram_peak <= '0;
      histogram_integral <= '0;
      issue_q <= 1'b0;
      simple_pending_q <= 1'b0;
      simple_user_q <= '0;
      result_pending_q <= 1'b0;
      result_user_q <= '0;
      result_data_q <= '0;
      capture_pending_q <= 1'b0;
      math_pending_q <= 1'b0;
      capture_raw_q <= '0;
      capture_left_q <= '0;
      capture_center_q <= '0;
      capture_right_q <= '0;
      capture_valid_q <= 1'b0;
      capture_overrange_q <= 1'b0;
      capture_timestamp_q <= '0;
      capture_integral_q <= '0;
      capture_flags_q <= '0;
      math_raw_q <= '0;
      math_delta_abs_q <= '0;
      math_divisor_q <= 16'd1;
      math_fallback_q <= 1'b1;
      math_timestamp_q <= '0;
      math_integral_q <= '0;
      math_flags_q <= '0;
      divider_user_q <= '0;
      divider_dividend_q <= '0;
      divider_divisor_q <= 16'd1;
    end else begin
      result_valid <= 1'b0;
      issue_q <= 1'b0;

      if (simple_pending_q) begin
        result_valid <= 1'b1;
        event_data <= {simple_user_q[69:22],
                       simple_user_q[21:8], 2'b00,
                       simple_user_q[93:70], simple_user_q[101:94]};
        histogram_peak <= simple_user_q[21:8];
        histogram_integral <= simple_user_q[93:70];
        simple_pending_q <= 1'b0;
        busy <= 1'b0;
      end

      if (result_pending_q) begin
        result_valid <= 1'b1;
        event_data <= {result_user_q[69:22], result_peak_q2,
                       result_user_q[93:70], result_flags};
        histogram_peak <= result_peak_q2[15:2];
        histogram_integral <= result_user_q[93:70];
        result_pending_q <= 1'b0;
        busy <= 1'b0;
      end

      if (divider_valid) begin
        result_user_q <= divider_user_out;
        result_data_q <= divider_data_out;
        result_pending_q <= 1'b1;
      end

      // Stage 1: capture the event candidate and metadata.  This isolates
      // acquisition's local-maximum selection from the arithmetic path.
      if (capture_pending_q) begin
        capture_pending_q <= 1'b0;
        math_pending_q <= 1'b1;
        math_raw_q <= capture_raw_q;
        math_delta_abs_q <= capture_delta_abs;
        math_divisor_q <= capture_fallback ? 16'd1 : capture_divisor;
        math_fallback_q <= capture_fallback;
        math_timestamp_q <= capture_timestamp_q;
        math_integral_q <= capture_integral_q;
        math_flags_q <= capture_flags_q;
      end

      // Stage 2/3: register the square before issuing the divider request.
      // The divider sees issue_q and its operands on the following clock,
      // matching the AXI-stream valid convention without assuming its output
      // latency.
      if (math_pending_q) begin
        math_pending_q <= 1'b0;
        divider_user_q <= {10'd0, math_divisor_q, math_flags_q,
                           math_integral_q, math_timestamp_q, math_raw_q,
                           math_fallback_q, 7'd0};
        divider_dividend_q <= math_fallback_q ? 28'd0 : math_square_value;
        divider_divisor_q <= math_fallback_q ? 16'd1 : math_divisor_q;
        issue_q <= 1'b1;
      end

      if (submit && !busy && !simple_pending_q) begin
        if (enable) begin
          capture_raw_q <= raw_peak;
          capture_left_q <= left_sample;
          capture_center_q <= center_sample;
          capture_right_q <= right_sample;
          capture_valid_q <= candidate_valid;
          capture_overrange_q <= invalid_overrange;
          capture_timestamp_q <= timestamp;
          capture_integral_q <= integral;
          capture_flags_q <= flags;
          capture_pending_q <= 1'b1;
          busy <= 1'b1;
        end else begin
          simple_user_q <= {10'd0, 16'd0, flags, integral, timestamp,
                            raw_peak, 1'b1, 7'd0};
          simple_pending_q <= 1'b1;
          busy <= 1'b1;
        end
      end
    end
  end
endmodule
