`timescale 1ns/1ps

// MCS2 transmit-side ACK coverage:
//   * a spectrum chunk that is not acknowledged is retransmitted,
//   * the retry counter advances and the ACK wait state stays armed,
//   * the retransmitted frame keeps the session/epoch/kind/chunk metadata the
//     ACK matcher keys on (checked on the DUT's latched descriptor registers),
//   * an ACK carrying another chunk index does not release the wait state,
//   * the matching ACK releases it, no further retransmission starts, and
//   * no UART frame or CRC error is reported throughout.
//
// Timing: the DUT runs with CLOCK_HZ=1_000_000 / BAUD_HZ=100_000, so one bit
// lasts exactly ten clocks and a 1100-byte chunk frame takes 110_000 clocks.
// Both protocol timers are CLOCK_HZ/10 = 100_000 clocks, so the retry path is
// reachable while the periodic status frames stay sparse enough not to starve
// the chunk.  A much smaller CLOCK_HZ queues a status frame every few hundred
// clocks and the chunk never completes; the real 125 MHz / 100 ms ratio avoids
// that.
module tb_mca_uart_ack_retry;
  localparam int  CLOCK_HZ     = 1_000_000;
  localparam int  BAUD_HZ      = 100_000;
  localparam int  BIT_CYCLES   = CLOCK_HZ / BAUD_HZ;          // 10
  localparam int  BYTE_CYCLES  = BIT_CYCLES * 10;             // 100
  localparam int  CHUNK_BINS   = 256;
  localparam int  FRAME_BYTES  = 16 + 40 + CHUNK_BINS*4 + 4;  // 1100
  localparam int  FRAME_CYCLES = FRAME_BYTES * BYTE_CYCLES;   // 110_000
  localparam int  RETRY_CYCLES = CLOCK_HZ / 10;               // 100_000
  localparam logic [31:0] EPOCH = 32'h0000_0007;
  localparam logic [31:0] SESSION = 32'h0000_0001;
  localparam logic [31:0] CONFIG_VERSION = 32'h0000_1234;

  logic clk = 0, rst_n = 0;
  always #5 clk = ~clk;   // 100 MHz, ten clocks per UART bit
  logic rxd = 1'b1, txd;

  logic         cmd_valid;
  logic [511:0] cmd_payload;
  logic [7:0]   cmd_len;
  logic         resp_valid = 1'b0;
  logic [519:0] resp_payload = '0;
  logic [7:0]   resp_len = '0;
  logic         resp_ready;
  logic         chunk_toggle = 1'b0;
  logic         chunk_ack_toggle;
  logic [7:0]   chunk_rd_index;
  logic [31:0]  crc_errors, frame_errors;

  mca_uart_protocol #(
    .CLOCK_HZ(CLOCK_HZ), .BAUD_HZ(BAUD_HZ),
    .BIN_COUNT(1024), .CHUNK_BINS(CHUNK_BINS)
  ) dut (
    .clk(clk), .rst_n(rst_n), .uart_rxd(rxd), .uart_txd(txd),
    .cmd_valid(cmd_valid), .cmd_payload(cmd_payload), .cmd_len(cmd_len),
    .cmd_ready(1'b0), .resp_valid(resp_valid), .resp_payload(resp_payload),
    .resp_len(resp_len), .resp_ready(resp_ready),
    .chunk_toggle(chunk_toggle), .chunk_ack_toggle(chunk_ack_toggle),
    .chunk_session(SESSION), .chunk_epoch(EPOCH),
    .chunk_config_version(CONFIG_VERSION), .chunk_kind(1'b0), .chunk_flags(8'h00),
    .chunk_shift(8'd2), .chunk_total_bins(16'd1024), .chunk_start(16'd0),
    .chunk_count(16'd256), .chunk_index(16'd0), .chunk_total(16'd4),
    .chunk_ticks(48'd0), .chunk_events(32'd0), .chunk_dropped(32'd0),
    .status_running(1'b0), .status_config_version(CONFIG_VERSION),
    .status_event_count(32'd0), .status_dropped_count(32'd0),
    .chunk_rd_index(chunk_rd_index), .chunk_rd_data(32'ha5a5_a5a5),
    .crc_error_count(crc_errors), .frame_error_count(frame_errors)
  );

  // ------------------------------------------------------------------
  // Minimal ACK transmitter.  Only the ACK frame is generated by the host
  // side; the chunk frames are checked through the DUT's own descriptor
  // registers, which is exactly what the ACK matcher compares against.
  // ------------------------------------------------------------------
  function automatic [31:0] crc_byte(input [31:0] crc, input [7:0] data);
    logic [31:0] c;
    integer b;
    begin
      c = crc ^ data;
      for (b = 0; b < 8; b = b + 1)
        c = c[0] ? ((c >> 1) ^ 32'hedb8_8320) : (c >> 1);
      crc_byte = c;
    end
  endfunction

  function automatic [7:0] be32(input logic [31:0] v, input int index);
    case (index)
      0: be32 = v[31:24]; 1: be32 = v[23:16];
      2: be32 = v[15:8];  default: be32 = v[7:0];
    endcase
  endfunction

  // Canonical 8N1 byte: the line is already idle (high), then one start-bit
  // period low, eight data-bit periods, one stop-bit period high.  Holding the
  // start bit for two periods would make the DUT drop the last data bit.
  task automatic send_byte(input logic [7:0] value);
    integer k;
    begin
      rxd = 1'b0;
      repeat (BIT_CYCLES) @(posedge clk);
      for (k = 0; k < 8; k = k + 1) begin
        rxd = value[k];
        repeat (BIT_CYCLES) @(posedge clk);
      end
      rxd = 1'b1;
      // Idle margin so the DUT's two-flop synchroniser sees a clean next start
      // bit instead of sampling it one clock early.
      repeat (2 * BIT_CYCLES) @(posedge clk);
    end
  endtask

  logic [7:0] ack_body [0:27];

  integer      ack_matches = 0;

  always_ff @(posedge clk) begin
    if (dut.ack_match_pulse)
      ack_matches <= ack_matches + 1;
  end

  task automatic send_ack(input logic [31:0] epoch_value,
                          input logic        kind_value,
                          input logic [15:0] chunk_value);
    logic [31:0] crc;
    integer i;
    begin
      ack_body[0]=8'h4d; ack_body[1]=8'h43; ack_body[2]=8'h53; ack_body[3]=8'h32;
      ack_body[4]=8'd2;  ack_body[5]=8'h03; ack_body[6]=8'd0; ack_body[7]=8'd16;
      ack_body[8]=8'd0;  ack_body[9]=8'd0;  ack_body[10]=8'd0; ack_body[11]=8'd1;
      ack_body[12]=8'd0; ack_body[13]=8'd12; ack_body[14]=8'd0; ack_body[15]=8'd0;
      ack_body[16]=be32(SESSION,0); ack_body[17]=be32(SESSION,1);
      ack_body[18]=be32(SESSION,2); ack_body[19]=be32(SESSION,3);
      ack_body[20]=be32(epoch_value,0); ack_body[21]=be32(epoch_value,1);
      ack_body[22]=be32(epoch_value,2); ack_body[23]=be32(epoch_value,3);
      ack_body[24]={7'd0, kind_value};
      ack_body[25]=chunk_value[15:8]; ack_body[26]=chunk_value[7:0];
      ack_body[27]=8'd0;
      crc = 32'hffff_ffff;
      for (i = 0; i < 28; i = i + 1) crc = crc_byte(crc, ack_body[i]);
      crc = ~crc;
      for (i = 0; i < 28; i = i + 1) send_byte(ack_body[i]);
      // The CRC-32 trailer is transmitted most-significant byte first, exactly
      // like the frame_byte()/be32_byte() pair inside mca_uart_protocol.
      for (i = 3; i >= 0; i = i - 1) send_byte(crc[8*i +: 8]);
    end
  endtask

  // ------------------------------------------------------------------
  // Helpers.
  // ------------------------------------------------------------------
  task automatic arm_chunk;
    begin
      chunk_toggle = 1'b1;
      repeat (16) @(posedge clk);
      chunk_toggle = 1'b0;
      repeat (8) @(posedge clk);
    end
  endtask

  task automatic wait_armed(input string what);
    integer budget;
    begin
      budget = 0;
      while (!dut.awaiting_ack && budget < 4 * FRAME_CYCLES) begin
        @(posedge clk);
        budget = budget + 1;
      end
      if (!dut.awaiting_ack)
        $fatal(1, "%s: transmitter never armed the ACK wait state (tx_index=%0d)",
               what, dut.tx_index);
    end
  endtask

  task automatic wait_for_retry(input logic [31:0] baseline, input string what);
    integer budget;
    begin
      budget = 0;
      while (dut.retry_count == baseline && budget < 4 * FRAME_CYCLES) begin
        @(posedge clk);
        budget = budget + 1;
      end
      if (dut.retry_count == baseline)
        $fatal(1, "%s: the ACK retry timer never fired", what);
    end
  endtask

  // The descriptor registers the transmitter latched for the frame being sent
  // and resent.  These are the fields the ACK matcher compares.
  task automatic check_latched_metadata(input string what);
    begin
      if (dut.sent_epoch !== EPOCH)
        $fatal(1, "%s: sent_epoch=%08x", what, dut.sent_epoch);
      if (dut.sent_kind !== 1'b0)
        $fatal(1, "%s: sent_kind=%0b", what, dut.sent_kind);
      if (dut.sent_chunk_index !== 16'd0)
        $fatal(1, "%s: sent_chunk_index=%0d", what, dut.sent_chunk_index);
      if (dut.meta_session !== SESSION)
        $fatal(1, "%s: meta_session=%08x", what, dut.meta_session);
      if (dut.meta_epoch !== EPOCH)
        $fatal(1, "%s: meta_epoch=%08x", what, dut.meta_epoch);
      if (dut.meta_config_version !== CONFIG_VERSION)
        $fatal(1, "%s: meta_config_version=%08x", what, dut.meta_config_version);
      if (dut.meta_kind !== 1'b0)
        $fatal(1, "%s: meta_kind=%0b", what, dut.meta_kind);
      if (dut.meta_bins !== 16'd1024)
        $fatal(1, "%s: meta_bins=%0d", what, dut.meta_bins);
      if (dut.meta_count !== 16'd256)
        $fatal(1, "%s: meta_count=%0d", what, dut.meta_count);
      if (dut.meta_index !== 16'd0)
        $fatal(1, "%s: meta_index=%0d", what, dut.meta_index);
      if (dut.tx_payload_len !== 16'(40 + CHUNK_BINS*4))
        $fatal(1, "%s: tx_payload_len=%0d", what, dut.tx_payload_len);
      if (dut.tx_is_chunk !== 1'b1)
        $fatal(1, "%s: the in-flight frame is not a spectrum chunk", what);
    end
  endtask

  integer      guard;
  logic [31:0] retry_before;

  initial begin
    repeat (5) @(posedge clk);
    rst_n = 1;
    repeat (5) @(posedge clk);

    // ===== arm a chunk and let the retry timer fire ====================
    arm_chunk();
    wait_armed("first chunk");

    retry_before = dut.retry_count;
    wait_for_retry(retry_before, "first chunk");
    if (!dut.awaiting_ack)
      $fatal(1, "the retransmission released the ACK wait state");
    // The retransmission must reuse the very same chunk descriptor.
    check_latched_metadata("first chunk retransmission");

    // ===== an ACK for another chunk must be ignored ====================
    send_ack(EPOCH, 1'b0, 16'd3);
    if (!dut.awaiting_ack)
      $fatal(1, "a stray ACK released the ACK wait state");
    if (dut.retry_count == retry_before)
      $fatal(1, "retransmissions stopped after a stray ACK");

    // ===== the matching ACK releases the wait state ====================
    send_ack(EPOCH, 1'b0, 16'd0);
    guard = 0;
    while (dut.awaiting_ack && guard < 4 * FRAME_CYCLES) begin
      @(posedge clk);
      guard = guard + 1;
    end
    if (dut.awaiting_ack)
      $fatal(1, "the matching ACK did not release the ACK wait state");
    if (ack_matches == 0)
      $fatal(1, "the matching ACK never reached the frame matcher");

    // ===== no further retransmission may start =========================
    // The ACK can be accepted while a retransmission is already in flight, so
    // let that frame drain first.  The accepted ACK resets the retry timer, so
    // no new frame may start until another full retry period has elapsed; a
    // 60% window is therefore a sound "no restart" check that cannot be
    // confused with the frame that was already running.
    guard = 0;
    while ((dut.tx_state != dut.TX_IDLE) && guard < 3 * FRAME_CYCLES) begin
      @(posedge clk);
      guard = guard + 1;
    end
    if (dut.tx_state != dut.TX_IDLE)
      $fatal(1, "the transmitter never returned to idle");
    retry_before = dut.retry_count;
    // A retransmission that was already in flight when the ACK was consumed
    // completes afterwards and re-arms the wait state for its own copy of the
    // chunk.  That is exactly the duplicate the protocol expects the host to
    // de-duplicate and ACK again, so the correct check is that a second ACK
    // clears it and that no *new* retry is scheduled afterwards.
    guard = 0;
    while (!dut.awaiting_ack && guard < 4 * FRAME_CYCLES) begin
      @(posedge clk);
      guard = guard + 1;
    end
    if (dut.awaiting_ack) begin
      retry_before = dut.retry_count;
      send_ack(EPOCH, 1'b0, 16'd0);
      guard = 0;
      while (dut.awaiting_ack && guard < 4 * FRAME_CYCLES) begin
        @(posedge clk);
        guard = guard + 1;
      end
      if (dut.awaiting_ack)
        $fatal(1, "the duplicate chunk ACK did not release the wait state");
    end
    // After the exchange settles the retry timer must stay disarmed.
    repeat (RETRY_CYCLES + RETRY_CYCLES / 2) @(posedge clk);
    if (dut.awaiting_ack)
      $fatal(1, "the ACK wait state re-armed without a new chunk");
    if (dut.retry_count != retry_before)
      $fatal(1, "a retransmission restarted after the matching ACK");

    // ===== a second chunk repeats the whole exchange ===================
    arm_chunk();
    wait_armed("second chunk");
    retry_before = dut.retry_count;
    wait_for_retry(retry_before, "second chunk");
    check_latched_metadata("second chunk retransmission");
    send_ack(EPOCH, 1'b0, 16'd0);
    guard = 0;
    while (dut.awaiting_ack && guard < 4 * FRAME_CYCLES) begin
      @(posedge clk);
      guard = guard + 1;
    end
    if (dut.awaiting_ack)
      $fatal(1, "the second chunk ACK did not release the wait state");

    if (frame_errors != 0)
      $fatal(1, "unexpected UART frame errors: %0d", frame_errors);
    if (crc_errors != 0)
      $fatal(1, "unexpected CRC errors: %0d", crc_errors);
    $display("tb_mca_uart_ack_retry PASS");
    $finish;
  end

  // Watchdog: every wait above is bounded, so a hang means a real bug.
  initial begin
    #200_000_000;
    $fatal(1, "tb_mca_uart_ack_retry TIMEOUT");
  end
endmodule
